// ---- Висячие предлоги ----
// Короткие слова (предлоги, союзы, частицы) приклеиваются к следующему слову
// неразрывным пробелом, тире — к предыдущему. Обрабатываются все тексты выше.
const SHORT = /(^|[\s(«])(в|во|и|к|ко|с|со|о|об|у|а|но|на|по|за|из|от|до|не|ни|для|без|при|под|над|что|как|это|же|ли|бы|его|её|их|мы|вы|он|она|они)\s+/giu;
const typo = (t: string) => t.replace(SHORT, "$1$2\u00a0").replace(SHORT, "$1$2\u00a0").replace(/ —/g, "\u00a0—").replace(/(\d) (\d{3})/g, "$1\u00a0$2").replace(/(\d) ([а-яA-Za-zK₽%])/g, "$1\u00a0$2");
type Deep = string | number | boolean | null | undefined | Deep[] | { [k: string]: Deep };
const fix = (o: Deep): Deep => {
  if (typeof o === "string") return typo(o);
  if (Array.isArray(o)) {
    o.forEach((v, i) => (o[i] = fix(v)));
    return o;
  }
  if (o && typeof o === "object") {
    for (const k of Object.keys(o)) if (k !== "tone" && k !== "color" && k !== "id" && k !== "href") o[k] = fix(o[k]);
    return o;
  }
  return o;
};
[site, price, hero, statement, modes, details, finish, specs, order, faq, footer].forEach((x) => fix(x as unknown as Deep));
